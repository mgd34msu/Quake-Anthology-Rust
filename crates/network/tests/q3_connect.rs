use qa_network::{
    commands::{
        packet,
        startup::{
            Q3Connectionless, read_q3_connectionless, write_q3_connect, write_q3_getchallenge,
        },
    },
    message::AdaptiveHuffman,
};

#[test]
fn q3_connect_matches_native_adaptive_packet_and_generated_key_order() {
    let mut codec = AdaptiveHuffman::new();
    let mut bytes = [0xcc; 2048];
    let length = write_q3_getchallenge(&mut bytes).unwrap();
    assert_eq!(&bytes[..length], b"\xff\xff\xff\xffgetchallenge");
    assert_eq!(bytes[length], 0xcc);
    let length = write_q3_connect(
        &mut codec,
        65535,
        -19,
        b"\\name\\Native Player\\rate\\25000",
        &mut bytes,
    )
    .unwrap();
    // Generated by the actual TypeScript Q3ClientAdmission.resend after its
    // challenge response, not by another codec retained in the Rust tests.
    assert_eq!(&bytes[..length], include_bytes!("fixtures/q3-connect.bin"));
    assert_eq!(bytes[length], 0xcc);
    assert_eq!(&bytes[..12], b"\xff\xff\xff\xffconnect ");
    let mut decoded = [0xcc; 1024];
    let decoded_length = codec.decompress(&bytes[12..length], &mut decoded).unwrap();
    assert_eq!(
        &decoded[..decoded_length],
        b"\"\\challenge\\-19\\qport\\65535\\protocol\\68\\name\\Native Player\\rate\\25000\""
    );
    assert_eq!(decoded[decoded_length], 0xcc);
}

#[test]
fn q3_handshake_fields_replace_the_first_exact_source_value_without_a_second_parser() {
    let mut codec = AdaptiveHuffman::new();
    let mut bytes = [0; 2048];
    let length = write_q3_connect(
        &mut codec,
        0,
        i32::MIN,
        b"\\protocol\\1\\protocol\\9\\qport\\2\\challenge\\3\\name\\A B",
        &mut bytes,
    )
    .unwrap();
    let mut decoded = [0; 1024];
    let count = codec.decompress(&bytes[12..length], &mut decoded).unwrap();
    assert_eq!(
        &decoded[..count],
        b"\"\\challenge\\-2147483648\\qport\\0\\protocol\\68\\protocol\\9\\name\\A B\""
    );
}

#[test]
fn q3_client_connectionless_replies_preserve_native_command_case_and_signed_prefix() {
    for (wire, expected) in [
        (
            b"\xff\xff\xff\xffChAlLeNgErEsPoNsE -19tail\n".as_slice(),
            Q3Connectionless::Challenge(-19),
        ),
        (
            b"\xff\xff\xff\xffchallengeResponse".as_slice(),
            Q3Connectionless::Challenge(0),
        ),
        (
            b"\xff\xff\xff\xffconnectResponse\0".as_slice(),
            Q3Connectionless::Accepted,
        ),
        (
            b"\xff\xff\xff\xffdisconnect\n".as_slice(),
            Q3Connectionless::Disconnect,
        ),
        (
            b"\xff\xff\xff\xffprint\nServer full\0ignored".as_slice(),
            Q3Connectionless::Print(b"Server full"),
        ),
        (
            b"\xff\xff\xff\xffprint\n".as_slice(),
            Q3Connectionless::Print(b""),
        ),
    ] {
        assert_eq!(read_q3_connectionless(wire).unwrap(), expected);
    }
    let wire = b"\xff\xff\xff\xffprint\nborrowed";
    let Q3Connectionless::Print(text) = read_q3_connectionless(wire).unwrap() else {
        panic!("print")
    };
    assert_eq!(text.as_ptr(), wire[10..].as_ptr());
    for wire in [
        b"\xff\xff\xff".as_slice(),
        b"\xff\xff\xff\xffchallengeResponse \"unfinished".as_slice(),
        b"\xff\xff\xff\xffunknown".as_slice(),
    ] {
        assert!(read_q3_connectionless(wire).is_err());
    }
}

#[test]
fn q3_connect_rejects_unrepresentable_info_and_reuses_scratch_after_capacity_failure() {
    let mut codec = AdaptiveHuffman::new();
    let mut output = [0xcc; 2048];
    for userinfo in [b"a\"b".as_slice(), b"a\nb", b"a\rb", b"a\0b"] {
        assert!(matches!(
            write_q3_connect(&mut codec, 1, 2, userinfo, &mut output),
            Err(packet::Error::Context)
        ));
    }
    assert!(matches!(
        write_q3_connect(&mut codec, 1, 2, &[b'x'; 1024], &mut output),
        Err(packet::Error::Count)
    ));
    let mut near_limit = b"\\name\\".to_vec();
    near_limit.extend_from_slice(&[b'x'; 979]);
    assert!(matches!(
        write_q3_connect(&mut codec, 1, 2, &near_limit, &mut output),
        Err(packet::Error::Count)
    ));
    near_limit.truncate(981);
    let length = write_q3_connect(&mut codec, 1, 2, &near_limit, &mut output).unwrap();
    let mut limit = [0; 1024];
    assert_eq!(
        codec.decompress(&output[12..length], &mut limit).unwrap(),
        1015
    );
    assert_eq!(limit[0], b'"');
    assert_eq!(limit[1014], b'"');
    assert!(write_q3_connect(&mut codec, 1, 2, b"\\name\\A", &mut [0; 12]).is_err());
    let count = write_q3_connect(&mut codec, 1, 2, b"\\name\\A", &mut output).unwrap();
    let mut decoded = [0; 1024];
    let count = codec.decompress(&output[12..count], &mut decoded).unwrap();
    assert_eq!(
        &decoded[..count],
        b"\"\\challenge\\2\\qport\\1\\protocol\\68\\name\\A\""
    );
}
