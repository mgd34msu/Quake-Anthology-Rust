/// Liquid profile selecting the table scale.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TurbulenceProfile {
    /// Quake 1 (full amplitude).
    Q1,
    /// Quake 2 (half amplitude).
    Q2,
}

/// Sample the source turbulence table (`sourceTurbulence`).
#[must_use]
pub fn source_turbulence(phase: f32, profile: TurbulenceProfile) -> f32 {
    let index = (phase * 256.0 / (2.0 * core::f32::consts::PI)) as i32 as usize & 255;
    let value = TURBULENCE[index];
    match profile {
        TurbulenceProfile::Q1 => value,
        TurbulenceProfile::Q2 => value * 0.5,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn zero_phase_is_zero() {
        assert_eq!(source_turbulence(0.0, TurbulenceProfile::Q1), 0.0);
        assert_eq!(source_turbulence(0.0, TurbulenceProfile::Q2), 0.0);
    }

    #[test]
    fn q2_is_half_q1() {
        let a = source_turbulence(1.0, TurbulenceProfile::Q1);
        let b = source_turbulence(1.0, TurbulenceProfile::Q2);
        assert!((a - b * 2.0).abs() < 1e-6);
    }

    #[test]
    fn table_peaks_at_eight() {
        let peak = TURBULENCE.iter().copied().fold(0.0_f32, f32::max);
        assert_eq!(peak, 8.0);
    }
}
