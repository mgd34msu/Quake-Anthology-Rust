/// Look up a native sphere point (`spherePoint`).
pub fn sphere_point(index: usize) -> Result<Vec3, Q1Error> {
    POINTS
        .get(index)
        .copied()
        .ok_or_else(|| q1_error("Invalid native sphere point"))
}

