/// Look up a base weapon definition (`q2WeaponDefinition`).
pub fn weapon_definition(name: Q2BaseWeaponName) -> Q2BaseWeaponDefinition {
    base_weapons()
        .into_iter()
        .find(|definition| definition.name == name)
        .expect("base weapon")
}

/// Look up a weapon definition by classname (`q2WeaponFromClassname`).
pub fn weapon_from_classname(classname: &str) -> Option<Q2BaseWeaponDefinition> {
    base_weapons()
        .into_iter()
        .find(|definition| definition.definition.classname == classname)
}
