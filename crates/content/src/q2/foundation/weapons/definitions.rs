//! Base weapon definitions (`src/content/q2/foundation/weapons/definitions.ts`).

use super::types::{Q2BaseWeaponDefinition, Q2BaseWeaponName, Q2WeaponDefinition};

fn definition(
    name: Q2BaseWeaponName,
    item: &str,
    classname: &str,
    ammo: Option<&str>,
    quantity: i32,
    warning: i32,
    view_model: &str,
    world_model: &str,
    player_model: i32,
    activate_last: i32,
    fire_last: i32,
    idle_last: i32,
    deactivate_last: i32,
    pauses: Vec<i32>,
    fires: Vec<i32>,
    repeating: bool,
) -> Q2BaseWeaponDefinition {
    Q2BaseWeaponDefinition {
        name,
        definition: Q2WeaponDefinition {
            name: name.as_str().to_string(),
            item: item.to_string(),
            classname: classname.to_string(),
            ammo: ammo.map(str::to_string),
            quantity,
            warning,
            view_model: view_model.to_string(),
            world_model: world_model.to_string(),
            player_model,
            activate_last,
            fire_last,
            idle_last,
            deactivate_last,
            pauses,
            fires,
            repeating,
        },
    }
}

